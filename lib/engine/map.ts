import { GUARDS, PROCESSES, WORKFLOWS, type GuardId, type ProcessId } from "./processes";

// Writes the built processes as Markdown, straight from the definitions. The
// process map (docs/PROCESS_MAP.md) carries this text between two markers, and a
// test fails when the two differ, so the document cannot drift from the data.

export function describeMachine(id: ProcessId) {
  const def = PROCESSES[id];
  return {
    id: def.id,
    name: def.name,
    what: def.what,
    record: def.record,
    kind: def.kind,
    initial: def.initial,
    states: def.states,
    transitions: def.transitions.map((t) => ({
      action: t.action,
      from: t.from,
      to: t.to,
      who: t.who,
      automatic: t.automatic,
      needsNote: t.needsNote,
      guards: t.guards.map((g) => ({ id: g, means: GUARDS[g as GuardId] ?? null })),
      what: t.what,
    })),
  };
}

// The process definitions as plain data: what `pcre process list` and the
// site's /export/processes.json both return.
export function describeProcesses() {
  return {
    workflows: WORKFLOWS.map((w) => ({ id: w.id, name: w.name, what: w.what, machines: w.machines, commands: w.commands, guide: w.guide })),
    machines: (Object.keys(PROCESSES) as ProcessId[]).map(describeMachine),
  };
}

export const MAP_START ="<!-- machines:start (generated by tools/process-map.ts; do not edit by hand) -->";
export const MAP_END = "<!-- machines:end -->";

const WHO = { agent: "agent", person: "person", either: "either" } as const;

function machine(id: ProcessId): string[] {
  const def = PROCESSES[id];
  const lines = [
    `#### ${def.name} (\`${def.id}\`)`,
    "",
    `${def.what} Kept in \`${def.record}\`${def.kind === "derived" ? "; its state is worked out from those records each time, never stored" : ""}.`,
    "",
    "| State | Meaning |",
    "|---|---|",
    ...Object.entries(def.states).map(([state, meaning]) => `| \`${state}\`${state === def.initial ? " (start)" : ""} | ${meaning} |`),
    "",
    "| Action | From | To | Who | Needs |",
    "|---|---|---|---|---|",
    ...def.transitions.map((t) => {
      const needs = [t.needsNote ? "a note" : null, ...t.guards.map((g) => `\`${g}\``)].filter(Boolean).join(", ");
      return `| \`${t.action}\` | ${t.from.map((f) => `\`${f}\``).join(", ")} | \`${t.to}\` | ${t.automatic ? "the engine, by itself" : WHO[t.who]} | ${needs || "—"} |`;
    }),
    "",
  ];
  return lines;
}

export function renderMachines(): string {
  const used = new Set<string>();
  const out: string[] = [];
  for (const w of WORKFLOWS) {
    out.push(`### ${w.name}`, "", w.what, "", `Commands: ${w.commands.map((c) => `\`pcre ${c} …\``).join(", ")}. Guide: \`${w.guide}\`.`, "");
    for (const id of w.machines) {
      out.push(...machine(id));
      for (const t of PROCESSES[id].transitions) for (const g of t.guards) used.add(g);
    }
  }
  out.push("### What can refuse a move", "", "| Guard | Meaning |", "|---|---|");
  for (const [id, meaning] of Object.entries(GUARDS)) if (used.has(id)) out.push(`| \`${id as GuardId}\` | ${meaning} |`);
  return out.join("\n");
}

// Replaces the generated block inside the process map's text.
export function withMachines(doc: string): string {
  const start = doc.indexOf(MAP_START);
  const end = doc.indexOf(MAP_END);
  if (start < 0 || end < start) throw new Error("The process map has lost its machines markers.");
  return `${doc.slice(0, start)}${MAP_START}\n\n${renderMachines()}\n\n${doc.slice(end)}`;
}
